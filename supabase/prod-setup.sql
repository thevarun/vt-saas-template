-- Production / fresh-environment setup
-- Run AFTER db:migrate (drizzle creates the tables first).
--
-- Execution order for a fresh environment:
--   1. npm run db:migrate            (creates the schema + tables)
--   2. psql -f supabase/seed.sql     (lookup seed data — REQUIRED before step 3
--                                     if you enable the reverse-trial trigger:
--                                     it RAISEs without the seeded subscription
--                                     tiers; the quota framework also needs the
--                                     'free' tier + its quota row)
--   3. psql -f supabase/prod-setup.sql  (this file — grants, trigger, FKs, RLS, CHECKs, updated_at)
--
-- This file contains Supabase-specific constructs that Drizzle ORM cannot manage:
--   1. Schema grants for anon / authenticated / service_role roles
--   2. Auth trigger (auto-create a user_preferences row on signup)
--   3. Cross-schema foreign keys (vt_saas.* -> auth.users)
--   4. Row-Level Security policies
--   5. CHECK constraints on text-typed enum columns (one illustrative example)
--   6. Generic updated_at trigger (set_updated_at, auto-attached per table)
--
-- Safe to re-run: every block uses CREATE OR REPLACE, IF NOT EXISTS, or DROP ... IF EXISTS.
--
-- SCHEMA NAME: this file assumes the DB_SCHEMA default `vt_saas` (see .env.example /
-- src/models/Schema.ts). If you set a different DB_SCHEMA, replace `vt_saas` throughout.
-- For a dedicated Supabase instance you may use `public` — in that case grants are
-- mostly redundant (Supabase auto-grants public) but the trigger / FKs / RLS still apply.
--
-- See docs/database-workflow.md for the three-home model and .claude/rules/database.md
-- for the must-not-break rules.

-- ============================================================
-- 1. SCHEMA GRANTS
-- ============================================================
-- Supabase only auto-grants on the public schema. A custom schema (created by
-- drizzle migration 0000 via CREATE SCHEMA) needs explicit grants, or the
-- Supabase JS client gets "permission denied" on every query.
-- service_role is required by admin clients (server-side jobs, admin APIs)
-- which bypass RLS for trusted operations.

GRANT USAGE ON SCHEMA vt_saas TO anon, authenticated, service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA vt_saas TO authenticated, service_role;
GRANT SELECT ON ALL TABLES IN SCHEMA vt_saas TO anon;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA vt_saas TO authenticated, service_role;

-- Ensure future tables also get grants
ALTER DEFAULT PRIVILEGES IN SCHEMA vt_saas GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA vt_saas GRANT SELECT ON TABLES TO anon;
ALTER DEFAULT PRIVILEGES IN SCHEMA vt_saas GRANT USAGE ON SEQUENCES TO authenticated, service_role;

-- ============================================================
-- 2. AUTH TRIGGER
-- ============================================================
-- Auto-create a user_preferences row whenever a new auth.users row is inserted.
-- user_preferences uses a separate `id` PK with a UNIQUE `user_id` (see
-- src/models/Schema.ts), so the trigger keys the row on user_id — `id` is
-- generated by the column default, and display_name / username stay NULL.
--
-- NAMESPACING: trigger names on auth.users share ONE namespace across every
-- project on a Supabase instance, and functions live in a schema. On a shared
-- dev instance hosting several forks, a fixed name like `on_auth_user_created`
-- + `public.handle_new_user()` means the last fork to run this file hijacks
-- every other fork's signup trigger. So the trigger name is prefixed with the
-- schema and the function lives IN the schema — the /init-downstream rename
-- sweep then namespaces both automatically, and forks coexist safely.

-- Legacy cleanup: earlier template versions used the un-namespaced names.
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
DROP FUNCTION IF EXISTS public.handle_new_user();

CREATE OR REPLACE FUNCTION vt_saas.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = ''
AS $$
BEGIN
  INSERT INTO "vt_saas"."user_preferences" (user_id, created_at, updated_at)
  VALUES (NEW.id, NOW(), NOW())
  ON CONFLICT (user_id) DO NOTHING;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS vt_saas_on_auth_user_created ON auth.users;
CREATE TRIGGER vt_saas_on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION vt_saas.handle_new_user();

