-- LIVE EXAMPLE: user_subscriptions.status and .billing_interval are text columns
-- with TS-side $type<> unions only (NOT pg enums — see
-- src/models/schema/user-subscriptions.ts), so the DB needs CHECKs to enforce them.
-- Keep the value lists in sync with userSubscriptionStatusEnum / billingIntervalEnum.
DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.table_constraints
    WHERE constraint_schema = 'vt_saas' AND constraint_name = 'user_subscriptions_status_check'
  ) THEN
    ALTER TABLE "vt_saas"."user_subscriptions"
      ADD CONSTRAINT user_subscriptions_status_check
      CHECK (status IN ('active', 'trial', 'expired', 'cancelled'));
  END IF;
END $$;

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.table_constraints
    WHERE constraint_schema = 'vt_saas' AND constraint_name = 'user_subscriptions_billing_interval_check'
  ) THEN
    ALTER TABLE "vt_saas"."user_subscriptions"
      ADD CONSTRAINT user_subscriptions_billing_interval_check
      CHECK (billing_interval IS NULL OR billing_interval IN ('monthly', 'yearly'));
  END IF;
END $$;

-- ============================================================
-- 6. UPDATED_AT TRIGGER
-- ============================================================
-- One generic function attached to EVERY table in the schema that has an
-- `updated_at` column. Self-maintaining: re-running this block picks up any
-- newly added table automatically. App code may still set updated_at; the
-- trigger always overrides it with the DB clock (NOW()), the more correct value.

CREATE OR REPLACE FUNCTION vt_saas.set_updated_at() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END $$;

-- The loop below queries information_schema and EXECUTEs dynamic SQL, so the
-- schema name lives in a single variable rather than hard-coded literals inside
-- format() strings. If you set a different DB_SCHEMA, change `schema_name` here
-- (and move set_updated_at into that schema) — not scattered string fragments.
DO $$
DECLARE
  schema_name text := 'vt_saas';
  r record;
BEGIN
  FOR r IN
    SELECT table_name FROM information_schema.columns
    WHERE table_schema = schema_name AND column_name = 'updated_at'
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%I_updated_at ON %I.%I', r.table_name, schema_name, r.table_name);
    EXECUTE format(
      'CREATE TRIGGER trg_%I_updated_at BEFORE UPDATE ON %I.%I '
      || 'FOR EACH ROW EXECUTE FUNCTION %I.set_updated_at()',
      r.table_name, schema_name, r.table_name, schema_name
    );
  END LOOP;
END $$;
