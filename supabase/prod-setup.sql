-- 5. CHECK CONSTRAINTS (text-typed enum guards)
-- ============================================================
-- When a column stores an enum as plain `text` (TS-side $type<...> only), there
-- is no DB-level guard against bad writes. Add a CHECK so the database enforces
-- it in every environment. Wrap in the same idempotent DO $$ IF NOT EXISTS idiom.
--
-- PATTERN (documentation only — intentionally NOT executed here). The template's
-- own enum columns (e.g. feedback.status) are real pg enums, so a CHECK would be
-- both redundant AND a trap: a CHECK that hard-codes the allowed values silently
-- rejects every write using a value added later via `ALTER TYPE ... ADD VALUE`.
-- Only add a CHECK for a column typed as plain `text` (no pg enum behind it).
-- Copy this block, drop the leading `-- `, and swap in your own table/column:
--
-- DO $$ BEGIN
